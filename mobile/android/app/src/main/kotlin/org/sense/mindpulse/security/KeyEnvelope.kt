package org.sense.mindpulse.security

import java.nio.ByteBuffer

/**
 * Versioned binary envelope that holds the SQLCipher passphrase, encrypted
 * with the Android Keystore wrapping key (AES-256-GCM). The wrapping key is
 * never stored here; it stays inside the Android Keystore.
 *
 * Format version 1 (big-endian, every length fixed):
 *
 * | offset | bytes | field                                                   |
 * |--------|-------|---------------------------------------------------------|
 * | 0      | 4     | magic `SNKE` (0x53 0x4E 0x4B 0x45)                      |
 * | 4      | 1     | format version (1)                                      |
 * | 5      | 1     | algorithm (1 = AES-256-GCM, Android Keystore key)       |
 * | 6      | 1     | IV length in bytes (12)                                 |
 * | 7      | 1     | GCM tag length in bytes (16)                            |
 * | 8      | 2     | ciphertext length incl. tag (48)                        |
 * | 10     | 12    | IV, generated by the Keystore for this encryption only  |
 * | 22     | 48    | ciphertext (32-byte passphrase) followed by the GCM tag |
 *
 * The 10-byte header is passed to GCM as additional authenticated data, so a
 * change to any header byte also fails authentication. Decoding accepts only
 * this exact header: a future format needs explicit migration code, never a
 * silent reinterpretation.
 */
internal object KeyEnvelope {
    private val MAGIC = byteArrayOf(0x53, 0x4E, 0x4B, 0x45)
    const val FORMAT_VERSION = 1
    const val ALGORITHM_AES256_GCM_KEYSTORE = 1
    const val IV_BYTES = 12
    const val TAG_BYTES = 16
    const val TAG_BITS = TAG_BYTES * 8
    const val PASSPHRASE_BYTES = 32
    const val CIPHERTEXT_BYTES = PASSPHRASE_BYTES + TAG_BYTES
    const val HEADER_BYTES = 10
    const val TOTAL_BYTES = HEADER_BYTES + IV_BYTES + CIPHERTEXT_BYTES

    /** The fixed header (also the GCM additional authenticated data). */
    fun header(): ByteArray =
        ByteBuffer.allocate(HEADER_BYTES)
            .put(MAGIC)
            .put(FORMAT_VERSION.toByte())
            .put(ALGORITHM_AES256_GCM_KEYSTORE.toByte())
            .put(IV_BYTES.toByte())
            .put(TAG_BYTES.toByte())
            .putShort(CIPHERTEXT_BYTES.toShort())
            .array()

    class Parsed(val header: ByteArray, val iv: ByteArray, val ciphertext: ByteArray)

    fun encode(iv: ByteArray, ciphertext: ByteArray): ByteArray {
        if (iv.size != IV_BYTES) throw EnvelopeFormatException("unexpected IV length")
        if (ciphertext.size != CIPHERTEXT_BYTES) throw EnvelopeFormatException("unexpected ciphertext length")
        return header() + iv + ciphertext
    }

    fun decode(bytes: ByteArray): Parsed {
        if (bytes.size != TOTAL_BYTES) throw EnvelopeFormatException("unexpected envelope length")
        val header = bytes.copyOfRange(0, HEADER_BYTES)
        if (!header.contentEquals(header())) throw EnvelopeFormatException("unsupported envelope header")
        val iv = bytes.copyOfRange(HEADER_BYTES, HEADER_BYTES + IV_BYTES)
        val ciphertext = bytes.copyOfRange(HEADER_BYTES + IV_BYTES, TOTAL_BYTES)
        return Parsed(header, iv, ciphertext)
    }
}

/** The envelope bytes are not a valid format-1 envelope. Never carries key material. */
class EnvelopeFormatException(message: String) : Exception(message)
